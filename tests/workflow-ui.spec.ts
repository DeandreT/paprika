import { test, expect } from '@playwright/test';
import { menuAction } from './navigation';
import { randomUUID } from 'node:crypto';
import { textPdf } from './fixtures';

test('reviewer publishes a type and release, previews a workflow draft and selects the published workflow', async ({ page, request }) => {
  const suffix = randomUUID().replaceAll('-', '');
  const typeId = `ui-type-${suffix}`, releaseId = `ui-release-${suffix}`;
  let workflowId = '';
  const keyword = `UIMARKER${suffix.toUpperCase()}`;
  async function savePublish() {
    await page.getByTestId('catalog-save').click();
    await expect(page.getByTestId('catalog-publish')).toBeEnabled();
    await page.getByTestId('catalog-publish').click();
    await expect(page.getByRole('status').filter({ hasText: 'Version published.' })).toBeVisible();
  }
  await page.goto('/');
  await menuAction(page, 'workflow-manager-toggle');
  await page.getByTestId('workflow-kind').getByRole('button', { name: 'Document type library', exact: true }).click();
  await page.getByRole('button', { name: 'New document type', exact: true }).click();
  await page.getByTestId('catalog-name').fill(`UI type ${suffix}`);
  await page.getByLabel('Stable ID', { exact: true }).fill(typeId);
  await page.getByLabel('Classification keywords', { exact: true }).fill(keyword);
  await savePublish();
  await page.getByTestId('workflow-kind').getByRole('button', { name: 'Releases', exact: true }).click();
  await page.getByRole('button', { name: 'New release', exact: true }).click();
  await page.getByTestId('catalog-name').fill(`UI release ${suffix}`);
  await page.getByLabel('Stable ID', { exact: true }).fill(releaseId);
  await page.getByRole('combobox', { name: `${typeId} version`, exact: true }).selectOption(`${typeId}@1`);
  await savePublish();
  await page.getByTestId('workflow-kind').getByRole('button', { name: 'Workflows', exact: true }).click();
  await page.getByRole('button', { name: 'New workflow', exact: true }).click();
  await expect(page.getByTestId('workflow-step')).toHaveText('Step 1 of 4 · Basics');
  await expect(page.getByTestId('workflow-next')).toBeDisabled();
  await expect(page.getByRole('navigation', { name: 'Packets' })).not.toBeVisible();
  await expect(page.getByRole('complementary', { name: 'Catalog versions' })).not.toBeVisible();
  await page.getByTestId('catalog-name').fill(`UI workflow ${suffix}`);
  await page.getByTestId('workflow-next').click();
  await expect(page.getByTestId('catalog-name')).not.toBeVisible();
  await expect(page.getByTestId('workflow-step')).toHaveText('Step 2 of 4 · Documents');
  await page.getByRole('combobox', { name: 'Document type release', exact: true }).selectOption('');
  await expect(page.getByTestId('workflow-next')).toBeDisabled();
  await page.getByRole('combobox', { name: 'Document type release', exact: true }).selectOption(`${releaseId}@1`);
  await page.getByTestId('workflow-next').click();
  await expect(page.getByTestId('workflow-step')).toHaveText('Step 3 of 4 · Review rules');
  await page.getByRole('combobox', { name: 'Default split policy', exact: true }).selectOption('fixed');
  await page.getByRole('spinbutton', { name: 'Pages per document', exact: true }).fill('0');
  await expect(page.getByTestId('workflow-next')).toBeDisabled();
  await page.getByRole('combobox', { name: 'Default split policy', exact: true }).selectOption('separate');
  await page.getByTestId('workflow-back').click();
  await expect(page.getByRole('combobox', { name: 'Document type release', exact: true })).toHaveValue(`${releaseId}@1`);
  await page.getByTestId('workflow-next').click();
  await expect(page.getByRole('combobox', { name: 'Default split policy', exact: true })).toHaveValue('separate');
  await page.getByTestId('workflow-next').click();
  await expect(page.getByTestId('workflow-step')).toHaveText('Step 4 of 4 · Finish');
  await expect(page.getByRole('button', { name: 'Run sample preview', exact: true })).toBeDisabled();
  await page.getByTestId('catalog-save').click();
  await expect(page.getByTestId('workflow-step')).toHaveText('Step 4 of 4 · Finish');
  await expect(page.getByTestId('catalog-publish')).toBeEnabled();
  await page.getByTestId('workflow-preview-files').setInputFiles({ name: 'synthetic-ui-preview.pdf', mimeType: 'application/pdf', buffer: textPdf([keyword, keyword]) });
  const accepted = page.waitForResponse(response => response.url().endsWith('/api/packets') && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Run sample preview', exact: true }).click();
  const previewResponse = await accepted;
  expect(previewResponse.ok()).toBe(true);
  const preview = await previewResponse.json();
  workflowId = preview.workflow.id;
  expect(workflowId).toBeTruthy();
  expect(preview.testRun).toBe(true);
  expect(preview.workflow.id).toBe(workflowId);
  await expect(page.getByTestId('test-run-badge')).toBeVisible();
  await expect.poll(async () => (await (await request.get(`/api/packets/${preview.id}`)).json()).status).toBe('review');
  const completed = await (await request.get(`/api/packets/${preview.id}`)).json();
  expect(completed.documents.map((document: any) => document.pageIds.length)).toEqual([1, 1]);
  expect(completed.pages.map((p: any) => p.predictedType)).toEqual([typeId, typeId]);

  await page.reload();
  await menuAction(page, 'workflow-manager-toggle');
  await page.getByTestId('workflow-kind').getByRole('button', { name: 'Workflows', exact: true }).click();
  await page.getByRole('button', { name: `Edit UI workflow ${suffix} version 1`, exact: true }).click();
  for (let i = 0; i < 3; i++) await page.getByTestId('workflow-next').click();
  await page.getByTestId('catalog-publish').click();
  await expect.poll(async () => {
    const c = await (await request.get('/api/workflows')).json();
    return c.entries.find((entry: any) => entry.kind === 'workflow' && entry.id === workflowId && entry.version === 1)?.status;
  }).toBe('published');
  await page.reload();
  await page.getByTestId('workflow-select').selectOption(`${workflowId}@1`);
  // The intake selector exposes the published configuration; draft previews stay marked.
  await expect(page.getByTestId('workflow-select')).toHaveValue(`${workflowId}@1`);
  await page.setViewportSize({ width: 390, height: 844 });
  await menuAction(page, 'workflow-manager-toggle');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
});

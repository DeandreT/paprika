import { test, expect } from '@playwright/test';
import { menuAction } from './navigation';
import { deflateSync } from 'node:zlib';

const headers = { 'X-paprika': '1' };

function syntheticPng(): Buffer {
  function chunk(type: string, bytes: Buffer): Buffer {
    const data = Buffer.concat([Buffer.from(type), bytes]);
    let crc = 0xffffffff;
    for (const b of data) {
      crc ^= b;
      for (let i = 0; i < 8; i++) crc = (crc >>> 1) ^ ((crc & 1) ? 0xedb88320 : 0);
    }
    const size = Buffer.alloc(4), checksum = Buffer.alloc(4);
    size.writeUInt32BE(bytes.length);
    checksum.writeUInt32BE((crc ^ 0xffffffff) >>> 0);
    return Buffer.concat([size, data, checksum]);
  }
  const header = Buffer.alloc(13);
  header.writeUInt32BE(64, 0); header.writeUInt32BE(64, 4);
  header[8] = 8; header[9] = 2;
  const rows = Buffer.alloc((64 * 3 + 1) * 64, 240);
  for (let y = 0; y < 64; y++) rows[y * (64 * 3 + 1)] = 0;
  return Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    chunk('IHDR', header), chunk('IDAT', deflateSync(rows)), chunk('IEND', Buffer.alloc(0)),
  ]);
}

test('upload actual PDF offline, review it, inspect revision history and download an approved document', async ({ page, request }) => {
  const config = await (await request.get('/api/config')).json();
  expect(config.mode).toBe('simulation');
  // Obtain a real PDF fixture generated by the application, not customer content.
  const demoResponse = await request.post('/api/packets/demo', { headers });
  expect(demoResponse.ok()).toBeTruthy();
  const demo = await demoResponse.json();
  const source = await request.get(demo.pages[0].previewUrl);
  expect(source.ok()).toBeTruthy();

  await page.goto('/');
  await menuAction(page, 'classification-advanced');
  await expect(page.getByRole('button', { name: /upload packet/i }).first()).toBeEnabled();
  const uploadEvent = page.waitForResponse(r => r.url().endsWith('/api/packets') && r.request().method() === 'POST');
  await page.getByTestId('upload-input').setInputFiles({
    name: 'offline-logistics-sample.pdf', mimeType: 'application/pdf', buffer: await source.body(),
  });
  const uploaded = await (await uploadEvent).json();
  expect(uploaded.mode).toBe('simulation');
  await expect(page.getByTestId('document-card').first()).toBeVisible();
  await expect(page.getByTestId('packet-name')).toContainText('offline-logistics-sample.pdf');
  await expect(page.getByText('Simulation · Local rules, no OCR').first()).toBeVisible();
  const details = page.getByTestId('classification-details');
  await expect(details.getByText('Rule match score')).not.toBeVisible();
  await details.getByText('Classification details', { exact: true }).click();
  await expect(details.getByText('Rule match score')).toBeVisible();
  await details.getByText('Classification details', { exact: true }).click();
  const packet = await (await request.get(`/api/packets/${uploaded.id}`)).json();
  expect(packet.status).toBe('review');
  expect(packet.pages.length).toBe(5);
  expect(packet.documents[0].pageIds.length).toBe(2);
  expect(packet.documents.length).toBeGreaterThanOrEqual(3);
  expect(packet.processing.model).toBe('local-simulation-1');

  // Keep the original proposal and a corrected draft visible as separate revisions.
  await page.getByTestId('document-type').first().selectOption('pod');
  await page.getByLabel('Business reference').first().fill('OFFLINE-REFERENCE-001');
  await page.getByTestId('history-toggle').click();
  await expect(page.getByTestId('history-revision')).toHaveCount(1);
  await expect(page.getByTestId('document-type').first()).toHaveValue('pod');
  await expect(page.getByLabel('Business reference').first()).toHaveValue('OFFLINE-REFERENCE-001');
  await expect(page.getByTestId('save-review')).toBeEnabled();
  await page.getByTestId('save-review').click();
  await expect(page.getByTestId('save-review')).toBeDisabled();
  await expect(page.getByTestId('history-revision')).toHaveCount(2);
  const history = await (await request.get(`/api/packets/${uploaded.id}/history`)).json();
  expect(history.map((h: { revision: number }) => h.revision)).toEqual([1, 2]);
  expect(history[0].documents[0].type).toBe('bol');
  expect(history[1].documents[0].type).toBe('pod');
  const beforeApproval = await request.get(`/api/packets/${uploaded.id}/documents/${packet.documents[0].id}/download`);
  expect(beforeApproval.status()).toBe(409);

  await page.getByTestId('approve-review').click();
  await expect(page.getByTestId('export-packet')).toBeEnabled();
  await expect(page.getByTestId('history-revision')).toHaveCount(3);
  const downloadEvent = page.waitForEvent('download');
  await page.getByTestId('document-download').first().click();
  const download = await downloadEvent;
  expect(download.suggestedFilename()).toMatch(/\.pdf$/i);
  expect(await download.failure()).toBeNull();

  const inbox = page.getByRole('navigation', { name: 'Packets' });
  await page.getByTestId('inbox-search').fill('OFFLINE-REFERENCE-001');
  await page.getByTestId('status-filter').selectOption('approved');
  await page.getByTestId('mode-filter').selectOption('simulation');
  await expect(inbox.getByRole('button')).toHaveCount(1);
  await expect(inbox.getByRole('button').first()).toContainText('offline-logistics-sample.pdf');
  await page.getByTestId('status-filter').selectOption('failed');
  await expect(inbox.getByRole('button')).toHaveCount(0);
});

test('offline image upload preserves the image and requires manual classification without invented OCR', async ({ page, request }) => {
  await page.goto('/');
  await menuAction(page, 'classification-advanced');
  await expect(page.getByRole('button', { name: /upload packet/i }).first()).toBeEnabled();
  const uploadEvent = page.waitForResponse(r => r.url().endsWith('/api/packets') && r.request().method() === 'POST');
  await page.getByTestId('upload-input').setInputFiles({ name: 'synthetic-scan.png', mimeType: 'image/png', buffer: syntheticPng() });
  const uploaded = await (await uploadEvent).json();
  await expect(page.getByTestId('document-card')).toHaveCount(1);
  const packet = await (await request.get(`/api/packets/${uploaded.id}`)).json();
  expect(packet.mode).toBe('simulation');
  expect(packet.pages[0].text).toBe('');
  expect(packet.pages[0].predictedType).toBe('unknown');
  expect(packet.pages[0].reviewReasons.join(' ')).toMatch(/OCR|text/i);
  await expect(page.getByTestId('document-type')).toHaveValue('unknown');
  await expect.poll(() => page.locator('.large-preview img').evaluate((img: HTMLImageElement) => img.complete && img.naturalWidth === 64)).toBe(true);
  await page.getByTestId('document-type').selectOption('receipt');
  await page.getByTestId('approve-review').click();
  await expect(page.getByTestId('document-download')).toBeEnabled();
  const approved = await (await request.get(`/api/packets/${uploaded.id}`)).json();
  expect(approved.documents[0].type).toBe('receipt');
  expect(approved.pages[0].predictedType).toBe('unknown');
  expect(approved.pages[0].text).toBe('');
});
